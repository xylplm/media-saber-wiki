<blockquote>
<p>📖 <strong>详细说明</strong>：关于Cron表达式的完整语法和更多示例，请参考：<a href="/docs/other/cron_rule">Cron表达式说明文档</a></p>
</blockquote>
<p>常用示例：</p>
<ul>
<li><code v-pre>0 2 * * *</code>：每天凌晨2点执行</li>
<li><code v-pre>0 */6 * * *</code>：每6小时执行一次</li>
<li><code v-pre>0 0 * * 0</code>：每周日凌晨执行</li>
