<li>点击&quot;刷新&quot;按钮获取最新数据</li>
<li>点击&quot;同步站点公告&quot;按钮获取最新的站点公告</li>
<li>在列表中查看各站点的公告内容</li>
<li>点击&quot;查看公告详情&quot;按钮查看公告详细信息</li>
</ol>
