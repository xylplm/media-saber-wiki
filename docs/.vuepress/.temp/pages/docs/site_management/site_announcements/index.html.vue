<li>点击&quot;定时任务&quot;按钮（时钟图标）可以配置定时同步任务。</li>
</ul>
<h3 id="👀-公告查看" tabindex="-1"><a class="header-anchor" href="#👀-公告查看"><span>👀 公告查看</span></a></h3>
