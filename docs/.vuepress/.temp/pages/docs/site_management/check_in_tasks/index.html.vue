<li>点击页面上的&quot;运行签到&quot;按钮（飞机图标），可以立即对所有已启用签到功能的站点执行签到操作。</li>
</ul>
<h3 id="🎯-单站点签到" tabindex="-1"><a class="header-anchor" href="#🎯-单站点签到"><span>🎯 单站点签到</span></a></h3>
<ul>
<li>在站点列表中，可以点击对应站点行的&quot;签到&quot;按钮（飞机图标），对该站点单独执行签到操作。</li>
</ul>
<h3 id="⏰-定时任务" tabindex="-1"><a class="header-anchor" href="#⏰-定时任务"><span>⏰ 定时任务</span></a></h3>
<ul>
<li>可以设置定时签到任务，系统将在指定时间自动执行签到操作。</li>
<li>点击&quot;定时任务&quot;按钮（时钟图标）可以配置定时签到任务。</li>
</ul>
<h3 id="📊-签到结果" tabindex="-1"><a class="header-anchor" href="#📊-签到结果"><span>📊 签到结果</span></a></h3>
<ul>
<li>✅ 签到成功或已签到的站点会显示绿色勾号图标</li>
<li>❌ 签到失败的站点会显示红色叉号图标</li>
<li>💬 签到信息会显示具体的签到结果说明</li>
</ul>
<h2 id="📖-使用方法" tabindex="-1"><a class="header-anchor" href="#📖-使用方法"><span>📖 使用方法</span></a></h2>
<ol>
<li>进入&quot;站点管理 - 签到任务&quot;页面</li>
<li>点击&quot;刷新&quot;按钮获取最新数据</li>
<li>点击&quot;运行签到&quot;按钮执行所有站点的签到任务</li>
<li>或者对特定站点点击行内的签到按钮进行单独签到</li>
<li>查看签到结果确认签到状态</li>
</ol>
