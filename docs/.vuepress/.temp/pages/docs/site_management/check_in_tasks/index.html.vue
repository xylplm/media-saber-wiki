<ul>
<li>站点必须在&quot;站点维护&quot;中正确配置Cookie等信息才能成功签到</li>
<li>部分站点可能需要配置User-Agent或自定义请求头</li>
<li>签到功能需要在站点维护中启用对应站点的签到开关</li>
</ul>
